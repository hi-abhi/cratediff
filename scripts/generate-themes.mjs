import { readFile, writeFile } from 'node:fs/promises';
import { bundledThemesInfo } from 'shiki/themes';

// Keep only names and appearance metadata in the synchronous settings bundle.
// Theme loaders and syntax definitions remain in Pierre's lazy ESM chunks.
const catalog = Object.fromEntries(['light', 'dark'].map(mode => [
  mode,
  bundledThemesInfo
    .filter(theme => theme.type === mode)
    .map(theme => ({ id: theme.id, label: theme.displayName }))
    .sort((left, right) => left.label.localeCompare(right.label, 'en')),
]));
const output = new URL('../js/shiki-themes.js', import.meta.url);
const contents = `// Generated by scripts/generate-themes.mjs from the installed Shiki catalog.\nexport const SHIKI_THEMES = ${JSON.stringify(catalog, null, 2)};\n`;
const previous = await readFile(output, 'utf8').catch(error => {
  if (error.code === 'ENOENT') return null;
  throw error;
});
// Trunk watches source files: avoid triggering another build for identical data.
if (previous !== contents) await writeFile(output, contents);
